function equipmentPage(opts: {
  key: EquipmentKey
  slug: string
  metaTitle: string
  metaDescription: string
  h1: string
  intro: string
  heroImage: string
  heroImageAlt: string
  uses: ArabicCard[]
  included: string[]
  guide: string[]
  faqs: Faq[]
  name: string
}): ArabicPage {
  return {
    path: `/ar/equipment/${opts.slug}`,
    enPath: `/equipment/${opts.slug}`,
    metaTitle: opts.metaTitle,
    metaDescription: opts.metaDescription,
    eyebrow: "تأجير مع مشغل · سلطنة عمان",
    h1: opts.h1,
    intro: opts.intro,
    heroImage: opts.heroImage,
    heroImageAlt: opts.heroImageAlt,
    sections: [
      { heading: `استخدامات ${opts.name}`, cards: opts.uses },
      { heading: "ماذا يشمل الإيجار", bullets: opts.included },
      { heading: "كيف تختار وكيف تحصل على عرض سعر سريع", paragraphs: opts.guide },
    ],
    faqs: opts.faqs,
    links: [
      ...arabicEquipment
        .filter((item) => item.key !== opts.key)
        .map((item) => ({ name: `تأجير ${item.name}`, href: item.path })),
      ...commonLinks,
    ],
    ctaHeading: `تحتاج ${opts.name}؟`,
    whatsappMessage: `السلام عليكم، أحتاج تأجير ${opts.name}.`,
    breadcrumb: [{ name: `تأجير ${opts.name}`, path: `/ar/equipment/${opts.slug}` }],
    serviceType: `تأجير ${opts.name}`,
    equipmentKey: opts.key,
  }
}

